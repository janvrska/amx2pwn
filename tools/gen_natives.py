"""Generate amx2pwn/omp_natives.py from the open.mp Pawn includes.

    git clone https://github.com/openmultiplayer/omp-stdlib
    python tools/gen_natives.py omp-stdlib [commit]

Every `native` and `forward On...` declaration is reduced to what the decompiler
needs: one letter per argument and the parameter names.

    i  plain value          f  Float            s  array / string
    r  &reference           fr &Float:reference m  variadic (...)
    p  player id            v  vehicle id       o  object id

The return letter is "f" for natives that return Float, otherwise "-".
"""

import glob
import os
import re
import sys

HEADER = '''\
# This Source Code Form is subject to the terms of the Mozilla Public
# License, v. 2.0. If a copy of the MPL was not distributed with this
# file, You can obtain one at https://mozilla.org/MPL/2.0/.
#
# Generated by tools/gen_natives.py from the open.mp Pawn includes
# (https://github.com/openmultiplayer/omp-stdlib%s). Do not edit by hand.
"""Native and callback signatures of SA-MP / open.mp, taken from the open.mp includes.

NATIVES:   name  argument-letters  return-letter  parameter-names
CALLBACKS: name  parameters (Float: tags and [] arrays kept)
"""

'''

# "native Name(...) = NewName;" is how open.mp keeps old SA-MP names (aliases), and
# "forward void:Name(...);" marks SA-MP natives that open.mp removed. Both are kept,
# because old scripts call them.
NATIVE_RE = re.compile(r"^native\s+(?:([A-Za-z_]\w*):)?([A-Za-z_]\w*)\s*\((.*)\)\s*(?:=\s*\w+\s*)?;$")
REMOVED_RE = re.compile(r"^forward\s+void:([A-Za-z_]\w*)\s*\((.*)\)\s*;$")
FORWARD_RE = re.compile(r"^forward\s+(?:([A-Za-z_]\w*):)?(On\w+)\s*\((.*)\)\s*;$")


def statements(text):
    """Top-level 'native'/'forward' declarations, joined across lines, comments removed.
    Complete one-line declarations inside comments come last: open.mp keeps a few
    SA-MP natives (GetPlayerPoolSize, ...) only as commented declarations for editors."""
    raw = text
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    yield from _statements(text)
    for line in raw.splitlines():
        s = re.sub(r"\s+", " ", line.strip())
        if NATIVE_RE.match(s):
            yield s


def _statements(text):
    cur = None
    for line in text.splitlines():
        s = line.strip()
        if cur is not None:
            cur += " " + s
        elif s.startswith(("native ", "forward ")):
            cur = s
        else:
            continue
        if cur.endswith(";"):
            yield re.sub(r"\s+", " ", cur)
            cur = None
        elif cur.endswith("{") or len(cur) > 2000:
            cur = None


def split_params(s):
    """Split on commas that are not inside {} or ()."""
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "({[":
            depth += 1
        elif ch in ")}]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def parse_param(p):
    """-> (letter, name, callback_form)"""
    p = p.split("=", 1)[0].strip()
    if p.endswith("..."):
        return "m", "...", "..."
    p = re.sub(r"^const\s+", "", p)
    ref = p.startswith("&")
    p = p.lstrip("&").strip()
    tag = None
    if ":" in p:
        tag, p = p.split(":", 1)
        tag = tag.strip()
    arr = "[" in p
    name = p.split("[", 1)[0].strip()
    if arr:
        letter = "s"
    elif tag == "Float":
        letter = "fr" if ref else "f"
    elif ref:
        letter = "r"
    elif name.lower().endswith("playerid"):
        letter = "p"
    elif name.lower().endswith("vehicleid"):
        letter = "v"
    elif name.lower() == "objectid":
        letter = "o"
    else:
        letter = "i"
    cb = ("Float:" if tag == "Float" else "") + name + ("[]" if arr else "")
    return letter, name, cb


def main():
    src = sys.argv[1]
    commit = sys.argv[2] if len(sys.argv) > 2 else ""
    natives, callbacks = {}, {}
    for path in sorted(glob.glob(os.path.join(src, "*.inc"))):
        with open(path, encoding="utf-8", errors="replace") as f:
            text = f.read()
        for st in statements(text):
            m = NATIVE_RE.match(st)
            r = REMOVED_RE.match(st)
            if m or r:
                tag, name, params = m.groups() if m else (None,) + r.groups()
                if name in natives or name.startswith("__"):
                    continue
                parsed = [parse_param(p) for p in split_params(params)]
                letters, names = [], []
                for letter, nm, _ in parsed:
                    letters.append(letter)
                    names.append(nm)
                    if letter == "m":
                        break
                natives[name] = ("f" if tag == "Float" else "-", letters, names)
                continue
            m = FORWARD_RE.match(st)
            if m and m.group(2) not in callbacks:
                callbacks[m.group(2)] = [parse_param(p)[2] for p in split_params(m.group(3))]
    out = [HEADER % ((", commit " + commit[:12]) if commit else "")]
    out.append("NATIVES = '''\n")
    for name in sorted(natives, key=str.lower):
        ret, letters, names = natives[name]
        out.append("%s %s %s %s\n" % (name, ",".join(letters) or "-", ret, ",".join(names) or "-"))
    out.append("'''\n\nCALLBACKS = '''\n")
    for name in sorted(callbacks, key=str.lower):
        out.append("%s %s\n" % (name, ",".join(callbacks[name]) or "-"))
    out.append("'''\n")
    dest = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "amx2pwn", "omp_natives.py")
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print("%d natives, %d callbacks -> %s" % (len(natives), len(callbacks), dest))


if __name__ == "__main__":
    main()
